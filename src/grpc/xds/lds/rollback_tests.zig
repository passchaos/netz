//! Publication must leave names, cached route data and accepted versions intact.
const std = @import("std");
const grpc = @import("../../mod.zig");
const ads = @import("../ads.zig");
const lds = @import("../lds.zig");
const rds = @import("../rds.zig");
const fixture = @import("testing.zig");
const route_fixture = @import("../rds/testing.zig");
const gpa = std.testing.allocator;
const manager = "{\"loadBalancingConfig\":[{\"xds_cluster_manager_experimental\":{\"children\":{\"cluster:a\":{\"childPolicy\":[{\"round_robin\":{}}]}}}}]}";
fn update(client: *ads.Client, url: []const u8, version: []const u8, bytes: []const u8) !ads.Update {
    const encoded = try ads.codec.encodeResponse(gpa, .{ .type_url = url, .version = version, .nonce = version, .resources = &.{.{ .type_url = url, .value = bytes }} }, 4096);
    defer gpa.free(encoded);
    var response = try ads.codec.decodeResponse(gpa, encoded, .{});
    errdefer response.deinit();
    return .{ .response = response, .token = try client.subscriptions.received(response.value) };
}
test "gRPC LDS failed publication rolls back RDS subscription listener cache and accepted versions" {
    var threaded = std.Io.Threaded.init(gpa, .{ .async_limit = .unlimited });
    defer threaded.deinit();
    const io = threaded.io();
    var failing = std.testing.FailingAllocator.init(gpa, .{});
    var channel = try grpc.SharedChannel.init(failing.allocator(), io, .{ .resolved = .{ .endpoints = &.{.{ .cleartext_ip = .{ .address = .{ .ip4 = .loopback(1) }, .hierarchical_path = &.{"cluster:a"} } }} } }, .{ .service_config_json = manager });
    defer channel.deinit();
    var sender = channel.sender();
    defer sender.deinit();
    var client = try ads.Client.init(gpa, sender, .{ .node = .{ .id = "test" } });
    defer client.deinit();
    var controller = try lds.Controller.init(gpa, .{ .listener_name = "frontend", .authority = "backend.test" });
    defer controller.deinit();
    try controller.subscribe(&client);
    const first = try fixture.encode(gpa, .{ .maximum_ms = 100 });
    defer gpa.free(first);
    var initial = try update(&client, lds.type_url, "l1", first);
    defer initial.deinit();
    try std.testing.expectError(error.AdsNotConnected, controller.applyWithDeadline(&client, initial, channel, .fromNow(io, .{ .clock = .awake, .raw = .fromSeconds(3) })));
    const route = try route_fixture.encode(gpa, "routes-a", &.{"backend.test"}, &.{.{ .prefix = "/" }}, null);
    defer gpa.free(route);
    var assignment = try update(&client, rds.type_url, "r1", route);
    defer assignment.deinit();
    try std.testing.expectError(error.AdsNotConnected, controller.applyWithDeadline(&client, assignment, channel, .fromNow(io, .{ .clock = .awake, .raw = .fromSeconds(3) })));
    const revision = channel.configurationRevision();
    const cached = controller.routes.?;
    const renamed = try fixture.encode(gpa, .{ .route_name = "routes-b", .maximum_ms = 20 });
    defer gpa.free(renamed);
    var candidate = try update(&client, lds.type_url, "l2", renamed);
    defer candidate.deinit();
    failing.fail_index = failing.alloc_index;
    const result = controller.applyWithDeadline(&client, candidate, channel, .fromNow(io, .{ .clock = .awake, .raw = .fromSeconds(3) }));
    failing.fail_index = std.math.maxInt(usize);
    try std.testing.expectError(error.OutOfMemory, result);
    try std.testing.expectEqual(revision, channel.configurationRevision());
    try std.testing.expectEqualStrings("routes-a", controller.listener.?.value.hcm.route_source.rds);
    try std.testing.expect(controller.routes.? == cached);
    try std.testing.expectEqualStrings("routes-a", client.subscriptions.find(rds.type_url).?.names[0]);
    try std.testing.expectEqualStrings("l1", client.acceptedVersion(lds.type_url).?);
    try std.testing.expectEqualStrings("r1", client.acceptedVersion(rds.type_url).?);
    try client.validateUpdate(candidate);
    try std.testing.expectError(error.Timeout, controller.applyWithDeadline(&client, candidate, channel, .fromNow(io, .{ .clock = .awake, .raw = .fromNanoseconds(-1) })));
    try std.testing.expectEqual(revision, channel.configurationRevision());
    try std.testing.expectError(error.AdsNotConnected, controller.applyWithDeadline(&client, candidate, channel, .fromNow(io, .{ .clock = .awake, .raw = .fromSeconds(3) })));
    try std.testing.expectEqualStrings("routes-b", client.subscriptions.find(rds.type_url).?.names[0]);
    try std.testing.expectEqualStrings("l2", client.acceptedVersion(lds.type_url).?);
    try std.testing.expectError(error.StaleDiscoveryResponse, controller.applyWithDeadline(&client, initial, channel, .fromNow(io, .{ .clock = .awake, .raw = .fromSeconds(3) })));
    const missing = try route_fixture.encode(gpa, "inline-missing", &.{"backend.test"}, &.{.{ .cluster = "missing" }}, null);
    defer gpa.free(missing);
    const inline_bytes = try fixture.encode(gpa, .{ .inline_rds = missing });
    defer gpa.free(inline_bytes);
    var invalid = try update(&client, lds.type_url, "l3", inline_bytes);
    defer invalid.deinit();
    const before = channel.configurationRevision();
    try std.testing.expectError(error.InvalidSharedOptions, controller.applyWithDeadline(&client, invalid, channel, .fromNow(io, .{ .clock = .awake, .raw = .fromSeconds(3) })));
    try std.testing.expectEqual(before, channel.configurationRevision());
    try std.testing.expectEqualStrings("routes-b", controller.listener.?.value.hcm.route_source.rds);
    try std.testing.expectEqualStrings("l2", client.acceptedVersion(lds.type_url).?);
}
