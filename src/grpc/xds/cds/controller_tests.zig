const std = @import("std");
const grpc = @import("../../mod.zig");
const fixture = @import("testing.zig");
const eds_fixture = @import("../eds/testing.zig");
const ads = @import("../ads.zig");
const cds = @import("../cds.zig");
const eds = @import("../eds.zig");
const gpa = std.testing.allocator;
fn update(client: *ads.Client, type_url: []const u8, version: []const u8, resources: []const ads.codec.Any) !ads.Update {
    const bytes = try ads.codec.encodeResponse(gpa, .{ .type_url = type_url, .version = version, .nonce = version, .resources = resources }, 4096);
    defer gpa.free(bytes);
    var response = try ads.codec.decodeResponse(gpa, bytes, .{});
    errdefer response.deinit();
    return .{ .response = response, .token = try client.subscriptions.received(response.value) };
}
test "gRPC CDS controller commits versions despite absent ACK stream and repolicies cached EDS" {
    var threaded = std.Io.Threaded.init(gpa, .{ .async_limit = .unlimited });
    defer threaded.deinit();
    const io = threaded.io();
    var destination = try grpc.SharedChannel.init(gpa, io, .{ .cleartext_ip = .{ .address = .{ .ip4 = .loopback(1) } } }, .{});
    defer destination.deinit();
    var sender = destination.sender();
    defer sender.deinit();
    var client = try ads.Client.init(gpa, sender, .{ .node = .{ .id = "test" } });
    defer client.deinit();
    var controller = try cds.Controller.init(gpa, .{ .cluster_name = "backend", .target = .{ .authority = "localhost" } });
    defer controller.deinit();
    try controller.subscribe(&client);
    const first = try fixture.cluster(gpa, "backend", "service-a", "");
    defer gpa.free(first);
    var event = try update(&client, cds.type_url, "c1", &.{.{ .type_url = cds.type_url, .value = first }});
    defer event.deinit();
    try std.testing.expectError(error.AdsNotConnected, controller.applyWithDeadline(&client, event, destination, .fromNow(io, .{ .clock = .awake, .raw = .fromSeconds(3) })));
    try std.testing.expectEqualStrings("c1", client.acceptedVersion(cds.type_url).?);
    try std.testing.expectEqualStrings("service-a", client.subscriptions.find(eds.type_url).?.names[0]);
    const assignment = try eds_fixture.encode(gpa, "service-a", &.{.{ .region = "r", .weight = 3, .endpoints = &.{.{ .port = 1001, .weight = 2 }} }}, null);
    defer gpa.free(assignment);
    var endpoints = try update(&client, eds.type_url, "e1", &.{.{ .type_url = eds.type_url, .value = assignment }});
    defer endpoints.deinit();
    try std.testing.expectError(error.AdsNotConnected, controller.applyWithDeadline(&client, endpoints, destination, .fromNow(io, .{ .clock = .awake, .raw = .fromSeconds(3) })));
    try std.testing.expectEqual(@as(usize, 1), destination.configuredEndpointCount());
    const changed = try fixture.cluster(gpa, "backend", "service-a", "\x30\x02\x52\x06\x0a\x04\x22\x02\x08\x05");
    defer gpa.free(changed);
    var policy = try update(&client, cds.type_url, "c2", &.{.{ .type_url = cds.type_url, .value = changed }});
    defer policy.deinit();
    try std.testing.expectError(error.AdsNotConnected, controller.applyWithDeadline(&client, policy, destination, .fromNow(io, .{ .clock = .awake, .raw = .fromSeconds(3) })));
    try std.testing.expect(!controller.cluster.?.value.policy.locality_weighted);
    try std.testing.expectEqual(@as(u32, 5), controller.cluster.?.value.max_concurrent_requests);
    try std.testing.expectEqual(@as(usize, 1), destination.configuredEndpointCount());
    const next = try fixture.cluster(gpa, "backend", "service-b", "");
    defer gpa.free(next);
    var switch_event = try update(&client, cds.type_url, "c3", &.{.{ .type_url = cds.type_url, .value = next }});
    defer switch_event.deinit();
    try std.testing.expectError(error.AdsNotConnected, controller.applyWithDeadline(&client, switch_event, destination, .fromNow(io, .{ .clock = .awake, .raw = .fromSeconds(3) })));
    try std.testing.expectEqual(@as(usize, 0), destination.configuredEndpointCount());
    try std.testing.expectEqualStrings("service-b", client.subscriptions.find(eds.type_url).?.names[0]);
    try std.testing.expect(controller.eds_image == null);
    const revision = destination.configurationRevision();
    var invalid = try update(&client, cds.type_url, "bad", &.{ .{ .type_url = cds.type_url, .value = next }, .{ .type_url = cds.type_url, .value = next } });
    defer invalid.deinit();
    try std.testing.expectError(error.DuplicateCdsResource, controller.applyWithDeadline(&client, invalid, destination, .fromNow(io, .{ .clock = .awake, .raw = .fromSeconds(3) })));
    try std.testing.expectEqual(revision, destination.configurationRevision());
    try std.testing.expectEqualStrings("c3", client.acceptedVersion(cds.type_url).?);
    var deletion = try update(&client, cds.type_url, "c4", &.{});
    defer deletion.deinit();
    try std.testing.expectError(error.AdsNotConnected, controller.applyWithDeadline(&client, deletion, destination, .fromNow(io, .{ .clock = .awake, .raw = .fromSeconds(3) })));
    try std.testing.expect(controller.cluster == null);
    var late = try update(&client, eds.type_url, "e2", &.{.{ .type_url = eds.type_url, .value = assignment }});
    defer late.deinit();
    try std.testing.expectError(error.AdsNotConnected, controller.applyWithDeadline(&client, late, destination, .fromNow(io, .{ .clock = .awake, .raw = .fromSeconds(3) })));
    try std.testing.expectEqual(@as(usize, 0), destination.configuredEndpointCount());
}

test "gRPC CDS controller publication failure discards staged EDS names and retains accepted cache" {
    var threaded = std.Io.Threaded.init(gpa, .{ .async_limit = .unlimited });
    defer threaded.deinit();
    const io = threaded.io();
    var failing = std.testing.FailingAllocator.init(gpa, .{});
    var destination = try grpc.SharedChannel.init(failing.allocator(), io, .{ .cleartext_ip = .{ .address = .{ .ip4 = .loopback(1) } } }, .{});
    defer destination.deinit();
    var sender = destination.sender();
    defer sender.deinit();
    var client = try ads.Client.init(gpa, sender, .{ .node = .{ .id = "test" } });
    defer client.deinit();
    var controller = try cds.Controller.init(gpa, .{ .cluster_name = "backend", .target = .{ .authority = "localhost" } });
    defer controller.deinit();
    try controller.subscribe(&client);
    const first = try fixture.cluster(gpa, "backend", "service-a", "");
    defer gpa.free(first);
    var event = try update(&client, cds.type_url, "c1", &.{.{ .type_url = cds.type_url, .value = first }});
    defer event.deinit();
    try std.testing.expectError(error.AdsNotConnected, controller.applyWithDeadline(&client, event, destination, .fromNow(io, .{ .clock = .awake, .raw = .fromSeconds(3) })));
    const bytes = try eds_fixture.encode(gpa, "service-a", &.{.{ .region = "r", .endpoints = &.{.{ .port = 1001 }} }}, null);
    defer gpa.free(bytes);
    var endpoints = try update(&client, eds.type_url, "e1", &.{.{ .type_url = eds.type_url, .value = bytes }});
    defer endpoints.deinit();
    try std.testing.expectError(error.AdsNotConnected, controller.applyWithDeadline(&client, endpoints, destination, .fromNow(io, .{ .clock = .awake, .raw = .fromSeconds(3) })));
    const revision = destination.configurationRevision();
    const original_image = controller.eds_image.?;
    const next = try fixture.cluster(gpa, "backend", "service-b", "");
    defer gpa.free(next);
    var switching = try update(&client, cds.type_url, "c2", &.{.{ .type_url = cds.type_url, .value = next }});
    defer switching.deinit();
    failing.fail_index = failing.alloc_index;
    const result = controller.applyWithDeadline(&client, switching, destination, .fromNow(io, .{ .clock = .awake, .raw = .fromSeconds(3) }));
    failing.fail_index = std.math.maxInt(usize);
    try std.testing.expectError(error.OutOfMemory, result);
    try std.testing.expectEqual(revision, destination.configurationRevision());
    try std.testing.expectEqual(@as(usize, 1), destination.configuredEndpointCount());
    try std.testing.expectEqualStrings("service-a", client.subscriptions.find(eds.type_url).?.names[0]);
    try std.testing.expectEqualStrings("service-a", controller.cluster.?.value.edsName());
    try std.testing.expect(controller.eds_image.?.ptr == original_image.ptr);
    try std.testing.expectEqualStrings("c1", client.acceptedVersion(cds.type_url).?);
    try client.validateUpdate(switching);
    try std.testing.expectError(error.StaleDiscoveryResponse, controller.applyWithDeadline(&client, event, destination, .fromNow(io, .{ .clock = .awake, .raw = .fromSeconds(3) })));
    try std.testing.expectError(error.Timeout, controller.applyWithDeadline(&client, switching, destination, .fromNow(io, .{ .clock = .awake, .raw = .fromNanoseconds(-1) })));
}
