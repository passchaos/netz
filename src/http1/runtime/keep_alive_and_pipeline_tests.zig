            self.count += 1;
            if (!request.must_close or request.keepAlive() or
                !std.mem.eql(u8, "payload", request.body) or
                request.header("content-length") != null)
            {
                return error.InvalidResponse;
            }
            return .{
                .headers = &.{.{
                    .name = "Connection",
                    .value = "keep-alive",
