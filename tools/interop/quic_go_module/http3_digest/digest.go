package main

import (
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"crypto/sha512"
	"encoding/base64"
	"errors"
	"fmt"
	"net/http"
	"strings"
)

var payload = []byte(strings.Repeat("HTTP3 digest content ", 512))
var generated = []byte(`{"hello": "world"}`)
var paths = []string{"/encoded", "/trailer", "/corrupt", "/head", "/range", "/stream", "/generated", "/finish"}
var digestMismatch = errors.New("digest mismatch")

func digestField(data []byte, algorithm string) string {
	var value []byte
	switch algorithm {
	case "sha-256":
		sum := sha256.Sum256(data)
		value = sum[:]
	case "sha-512":
		sum := sha512.Sum512(data)
		value = sum[:]
	default:
		panic("unsupported fixture algorithm")
	}
	return algorithm + "=:" + base64.StdEncoding.EncodeToString(value) + ":"
}

// Verify the canonical RFC9530 fields produced by the native fixture. This
// independent oracle intentionally accepts only the generated Byte Sequences,
// not a general Structured Fields grammar.
func verifyFields(data []byte, sections ...[]string) error {
	a := sha256.Sum256(data)
	b := sha512.Sum512(data)
	return verifySums(map[string][]byte{"sha-256": a[:], "sha-512": b[:]}, sections...)
}

func verifySums(sums map[string][]byte, sections ...[]string) error {
	checked := 0
	for _, section := range sections {
		for _, field := range section {
			for _, member := range strings.Split(field, ",") {
				algorithm, encoded, ok := strings.Cut(strings.TrimSpace(member), "=")
				if !ok || len(encoded) < 2 || encoded[0] != ':' || encoded[len(encoded)-1] != ':' {
					return fmt.Errorf("invalid generated field %q", member)
				}
				decoded, err := base64.StdEncoding.DecodeString(encoded[1 : len(encoded)-1])
				if err != nil {
					return err
				}
				expectedBytes, ok := sums[algorithm]
				if !ok {
					return fmt.Errorf("unsupported generated algorithm %q", algorithm)
				}
				if !bytes.Equal(decoded, expectedBytes) {
					return digestMismatch
				}
				checked++
			}
		}
	}
	if checked == 0 {
		return errors.New("missing generated digest")
	}
	return nil
}

func reply(path string) ([]byte, http.Header, http.Header, error) {
	content := payload
	headers, trailers := http.Header{}, http.Header{}
	switch path {
	case "/encoded":
		var buffer bytes.Buffer
		writer := gzip.NewWriter(&buffer)
		if _, err := writer.Write(payload); err != nil {
			return nil, nil, nil, err
		}
		if err := writer.Close(); err != nil {
			return nil, nil, nil, err
		}
		content = buffer.Bytes()
		headers.Set("Content-Encoding", "gzip")
		headers.Set("Content-Digest", digestField(content, "sha-256"))
	case "/trailer":
		trailers.Set("Content-Digest", digestField(content, "sha-512"))
	case "/corrupt":
		headers.Set("Content-Digest", digestField(content, "sha-256")+", "+digestField([]byte("different"), "sha-512"))
	case "/head":
		headers.Set("Content-Digest", digestField(nil, "sha-256"))
		headers.Set("Repr-Digest", digestField(payload, "sha-512"))
		headers.Set("Content-Length", fmt.Sprint(len(payload)))
	case "/range":
		content = payload[8:72]
		headers.Set("Content-Digest", digestField(content, "sha-256"))
		headers.Set("Repr-Digest", digestField(payload, "sha-512"))
		headers.Set("Content-Range", fmt.Sprintf("bytes 8-71/%d", len(payload)))
	case "/stream":
		trailers.Set("Content-Digest", digestField(content, "sha-256")+", "+digestField(content, "sha-512"))
	case "/generated":
		content = []byte("verified")
		headers.Set("Content-Digest", digestField(content, "sha-256"))
	case "/finish":
		content = []byte("done")
		headers.Set("Content-Digest", digestField(content, "sha-512"))
	default:
		return nil, nil, nil, fmt.Errorf("unexpected path %q", path)
	}
	return content, headers, trailers, nil
}
