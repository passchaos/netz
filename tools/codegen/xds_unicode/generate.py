#!/usr/bin/env python3
"""Generate endian-independent native RE2 Unicode lookup data from a pinned source."""
import argparse,hashlib,json,re,struct,urllib.request
from pathlib import Path
REVISION='2da0056814cf180480a19f5cf811e7e1c054bf6d'
ROOT=Path(__file__).resolve().parents[3]
OUTPUT=ROOT/'src/grpc/xds/routing/regex/unicode'
def main():
 parser=argparse.ArgumentParser();parser.add_argument('--verify',action='store_true');args=parser.parse_args()
 files={name:urllib.request.urlopen(f'https://raw.githubusercontent.com/google/re2/{REVISION}/{name}',timeout=20).read() for name in ['re2/unicode_groups.cc','re2/unicode_casefold.cc','LICENSE']}
 groups_source=files['re2/unicode_groups.cc'].decode();fold_source=files['re2/unicode_casefold.cc'].decode()
 ranges={name:[tuple(map(int,pair)) for pair in re.findall(r'\{\s*(\d+),\s*(\d+)\s*\}',data)] for name,data in re.findall(r'static const URange(?:16|32) (\w+)\[\] = \{(.*?)\};',groups_source,re.S)}
 groups=re.findall(r'\{ "([^"]+)", \+1, (\w+), (\d+), (\w+), (\d+) \}',groups_source)
 blob=bytearray();entries=[]
 for name,low,nlow,high,nhigh in groups:
  values=ranges.get(low,[])+ranges.get(high,[]);assert len(values)==int(nlow)+int(nhigh)
  assert all(a<=b for a,b in values)
  entries.append(f'    .{{ .name = "{name}", .offset = {len(blob)}, .count = {len(values)} }},')
  blob.extend(b''.join(struct.pack('<II',a,b) for a,b in values))
 assert [x[0] for x in groups]==sorted(x[0] for x in groups)
 fold_data=re.search(r'const CaseFold unicode_casefold\[\] = \{(.*?)\};',fold_source,re.S)[1]
 fold=bytearray()
 for a,b,delta in re.findall(r'\{\s*(\d+),\s*(\d+),\s*([^ }]+)\s*\}',fold_data):
  value={'EvenOdd':1,'OddEven':-1}.get(delta)
  if value is None:value=int(delta)
  fold.extend(struct.pack('<IIi',int(a),int(b),value))
 generated={
 'groups.bin':bytes(blob),'fold.bin':bytes(fold),'LICENSE.re2':files['LICENSE'],
 'groups.zig':('// Generated by tools/codegen/xds_unicode/generate.py. RE2 BSD license: LICENSE.re2.\n'+
 'pub const entries = [_]@import("../unicode.zig").Entry{\n'+'\n'.join(entries)+'\n};\n').encode(),
 'source.json':(json.dumps({'revision':REVISION,'source_sha256':{name:hashlib.sha256(data).hexdigest() for name,data in files.items()},'unicode_groups':len(groups),'fold_ranges':len(fold)//12},indent=2)+'\n').encode()}
 for name,data in generated.items():
  path=OUTPUT/name
  if args.verify:assert path.read_bytes()==data,name
  else:path.write_bytes(data)
 print(json.dumps({'groups':len(groups),'fold_ranges':len(fold)//12,'verified':args.verify}))
if __name__=='__main__':main()
